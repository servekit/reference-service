// emit.go — shared emission helpers: collated ordering and Go source
// writers for the per-domain tables consumed by internal/data.
package main

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"sort"
	"strings"

	"golang.org/x/text/collate"
	"golang.org/x/text/language"
)

// locales mirrors data.Locales (kept in sync by a generator self-check).
var locales = []string{"zh-Hans", "zh-Hant", "ja", "ko", "en", "fr", "de", "pt", "es", "ar", "ru"}

// collatedOrder returns keys sorted by their name under the locale's CLDR
// collation — the per-locale display order baked into the generated tables.
func collatedOrder(locale string, names map[string]string) []string {
	c := collate.New(language.MustParse(locale))
	keys := make([]string, 0, len(names))
	for k := range names {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool {
		if v := c.CompareString(names[keys[i]], names[keys[j]]); v != 0 {
			return v < 0
		}
		return keys[i] < keys[j]
	})
	return keys
}

// writer accumulates a generated Go file.
type writer struct {
	sb strings.Builder
}

func newWriter(generatedBy string) *writer {
	w := &writer{}
	w.line("// Code generated by tools/gen (%s). DO NOT EDIT.", generatedBy)
	w.line("")
	w.line("package data")
	w.line("")
	return w
}

func (w *writer) line(format string, args ...any) {
	fmt.Fprintf(&w.sb, format+"\n", args...)
}

func (w *writer) save(path string) error {
	return os.WriteFile(path, []byte(w.sb.String()), 0o644)
}

// emitNames writes   var <name> = map[string]map[string]string{...}
// keyed locale -> code -> name, locales in canonical order.
func (w *writer) emitNames(name string, perLocale map[string]map[string]string) {
	w.line("var %s = map[string]map[string]string{", name)
	for _, l := range locales {
		m := perLocale[l]
		w.line("\t%q: {", l)
		for _, k := range sortedKeys(m) {
			w.line("\t\t%q: %q,", k, m[k])
		}
		w.line("\t},")
	}
	w.line("}")
	w.line("")
}

// emitOrder writes   var <name> = map[string][]string{...}
func (w *writer) emitOrder(name string, perLocale map[string][]string) {
	w.line("var %s = map[string][]string{", name)
	for _, l := range locales {
		w.line("\t%q: {%s},", l, quoteJoin(perLocale[l]))
	}
	w.line("}")
	w.line("")
}

func quoteJoin(ss []string) string {
	parts := make([]string, len(ss))
	for i, s := range ss {
		parts[i] = fmt.Sprintf("%q", s)
	}
	return strings.Join(parts, ", ")
}

func sortedKeys[T any](m map[string]T) []string {
	ks := make([]string, 0, len(m))
	for k := range m {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	return ks
}

// checkDataLocales asserts internal/data/data.go Locales matches the
// generator's locale list, so the two can never drift silently.
func checkDataLocales(dataDir string) error {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, dataDir+"/data.go", nil, 0)
	if err != nil {
		return err
	}
	var got []string
	for _, d := range f.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, spec := range gd.Specs {
			vs, ok := spec.(*ast.ValueSpec)
			if !ok || len(vs.Names) == 0 || vs.Names[0].Name != "Locales" || len(vs.Values) == 0 {
				continue
			}
			cl, ok := vs.Values[0].(*ast.CompositeLit)
			if !ok {
				continue
			}
			for _, e := range cl.Elts {
				if bl, ok := e.(*ast.BasicLit); ok {
					got = append(got, strings.Trim(bl.Value, "`\""))
				}
			}
		}
	}
	if strings.Join(got, ",") != strings.Join(locales, ",") {
		return fmt.Errorf("data.Locales %v != generator locales %v", got, locales)
	}
	return nil
}
